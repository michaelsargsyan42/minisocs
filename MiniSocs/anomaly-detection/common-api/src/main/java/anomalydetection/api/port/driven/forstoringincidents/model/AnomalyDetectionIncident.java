package anomalydetection.api.port.driven.forstoringincidents.model;

/**
 * This record models the information provided when detecting an anomaly.
 */
public class AnomalyDetectionIncident {
	/**
	 * the identifier generated by the database.
	 */
	private int id;
	/**
	 * the creation instant of the message posted. This is the string version for
	 * the database.
	 */
	private String instant;
	/**
	 * the name of type of the anomaly that was detected.
	 */
	private String type;
	/**
	 * the name of the social name.
	 */
	private String snname;
	/**
	 * the user's pseudo.
	 */
	private String pseudo;
	/**
	 * the content of the posted message.
	 */
	private String content;

	/**
	 * gets the identifier.
	 * 
	 * @return the value.
	 */
	public int getId() {
		return id;
	}

	/**
	 * sets the identifier.
	 * 
	 * @param id the new identifier.
	 */
	public void setId(final int id) {
		this.id = id;
	}

	/**
	 * gets the instant.
	 * 
	 * @return the value.
	 */
	public String getInstant() {
		return instant;
	}

	/**
	 * sets the instant.
	 * 
	 * @param instant the new value.
	 */
	public void setInstant(final String instant) {
		this.instant = instant;
	}

	/**
	 * gets the anomaly type.
	 * 
	 * @return the value.
	 */
	public String getType() {
		return type;
	}

	/**
	 * sets the anomaly type.
	 * 
	 * @param anomalyType the new value.
	 */
	public void setType(final String anomalyType) {
		this.type = anomalyType;
	}

	/**
	 * gets the name of the social network.
	 * 
	 * @return the value.
	 */
	public String getSnname() {
		return snname;
	}

	/**
	 * sets the name of the social network.
	 * 
	 * @param snName the new value.
	 */
	public void setSnname(final String snName) {
		this.snname = snName;
	}

	/**
	 * gets the user's pseudo.
	 * 
	 * @return the value.
	 */
	public String getPseudo() {
		return pseudo;
	}

	/**
	 * sets the user's pseudo.
	 * 
	 * @param pseudo the new value.
	 */
	public void setPseudo(final String pseudo) {
		this.pseudo = pseudo;
	}

	/**
	 * gets the content.
	 * 
	 * @return the value.
	 */
	public String getContent() {
		return content;
	}

	/**
	 * sets the content.
	 * 
	 * @param content the new value.
	 */
	public void setContent(final String content) {
		this.content = content;
	}

	@Override
	public String toString() {
		return "AnomalyDetectionIncident [id=" + id + ", instant=" + instant + ", type=" + type
				+ ", snname=" + snname + ", pseudo=" + pseudo + ", content=" + content + "]";
	}
}
